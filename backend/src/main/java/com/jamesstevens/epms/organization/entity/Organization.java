
package com.jamesstevens.epms.organization.entity;

import com.jamesstevens.epms.common.persistence.PostgresUuidV7;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import java.time.ZoneOffset;
import java.time.OffsetDateTime;
import java.util.UUID;

/**
 * JPA persistence entity representing the organization associated
 * with an EPMS installation.
 *
 * <p>Maps to the {@code organizations} table defined in the Flyway
 * V1 migration. EPMS is a single-organization application, meaning
 * each installation supports at most one organization record.
 *
 * <p>The database enforces this restriction through the
 * {@code ux_organizations_single_instance} unique index.
 * The service layer must also prevent attempts to create
 * additional organizations.
 *
 * <p>The entity stores organization identity, descriptive
 * information, active status, audit information, timestamps,
 * and an optimistic locking version.
 *
 * <p>This entity is an internal persistence model and must not
 * be exposed directly through REST API responses. Organization
 * DTOs define the public API contract.
 *
 * @see com.jamesstevens.epms.organization.dto.CreateOrganizationRequest
 * @see com.jamesstevens.epms.organization.dto.UpdateOrganizationRequest
 * @see com.jamesstevens.epms.organization.dto.OrganizationResponse
 */
@Entity
@Table(name = "organizations")
public class Organization {

    /**
     * Unique identifier for the organization.
     *
     * <p>Generated by PostgreSQL using its native {@code uuidv7()}
     * function through {@link PostgresUuidV7}.
     *
     * <p>Hibernate obtains the UUID before executing the INSERT
     * statement and includes the generated identifier in the
     * organization record.
     *
     * <p>The database also defines {@code uuidv7()} as the column
     * default for inserts performed outside Hibernate.
     *
     * <p>The identifier must not change after creation.
     */
    @Id
    @PostgresUuidV7
    @Column(
            name = "organization_id",
            nullable = false,
            updatable = false
    )
    private UUID organizationId;

    /**
     * Identifier of the user who originally created the organization.
     *
     * <p>Nullable to support initial organization setup before
     * a user account is available.
     */
    @Column(name = "created_by_user_id")
    private UUID createdByUserId;

    /**
     * Identifier of the user who most recently modified
     * the organization.
     *
     * <p>Audit attribution will be managed by the service layer
     * when authenticated user information becomes available.
     */
    @Column(name = "updated_by_user_id")
    private UUID updatedByUserId;

    /**
     * Organization name.
     *
     * <p>Required, limited to 200 characters, and must not
     * consist entirely of whitespace.
     *
     * <p>Input validation is defined in the request DTOs.
     * The database independently enforces the nonblank constraint.
     */
    @Column(
            name = "name",
            nullable = false,
            length = 200
    )
    private String name;

    /**
     * Optional description of the organization.
     *
     * <p>Mapped to PostgreSQL {@code TEXT}, allowing
     * variable-length descriptive content.
     */
    @Column(
            name = "description",
            columnDefinition = "TEXT"
    )
    private String description;

    /**
     * Indicates whether the organization is active.
     *
     * <p>New organizations are active by default.
     * Active status is managed separately from general
     * organization detail updates.
     *
     * <p>This field remains mutable to support future
     * organization activation and deactivation operations.
     */
    @Column(
            name = "is_active",
            nullable = false
    )
    private boolean active = true;

    /**
     * Timestamp indicating when the organization was created.
     *
     * <p>The database provides a {@code CURRENT_TIMESTAMP}
     * default for inserts performed directly through PostgreSQL.
     * When Hibernate persists a new organization, the
     * {@code @PrePersist} lifecycle callback initializes this
     * field using the current UTC timestamp.
     *
     * <p>The creation timestamp is immutable after persistence.
     * The {@code updatable = false} mapping prevents Hibernate
     * from including this field in subsequent UPDATE statements.
     */
    @Column(
            name = "created_at",
            nullable = false,
            updatable = false
    )
    private OffsetDateTime createdAt;

    /**
     * Timestamp indicating when the organization was last modified.
     *
     * <p>The database provides a {@code CURRENT_TIMESTAMP}
     * default for inserts performed directly through PostgreSQL.
     *
     * <p>When Hibernate persists a new organization, the
     * {@code @PrePersist} lifecycle callback initializes this
     * field to the same UTC timestamp as {@code createdAt}.
     *
     * <p>When Hibernate updates an existing organization, the
     * {@code @PreUpdate} lifecycle callback refreshes this
     * field using the current UTC timestamp.
     *
     * <p>The creation timestamp remains unchanged during updates.
     */
    @Column(
            name = "updated_at",
            nullable = false
    )
    private OffsetDateTime updatedAt;


    /**
     * Optimistic locking version managed by Hibernate.
     *
     * <p>Hibernate uses this value to detect conflicting updates
     * and prevent one transaction from silently overwriting
     * changes committed by another transaction.
     *
     * <p>Application code must not modify this field directly.
     */
    @Version
    @Column(
            name = "version",
            nullable = false
    )
    private Long version;

    /**
     * Constructs an Organization instance for JPA.
     *
     * <p>JPA requires a public or protected no-argument
     * constructor to instantiate entities during persistence
     * operations.
     *
     * <p>Application code should use a dedicated constructor
     * or factory method, which will be implemented separately.
     */
    protected Organization() {
        // Required by JPA.
    }

    /**
     * Creates a new organization with its initial business information.
     *
     * <p>The organization identifier is generated by PostgreSQL
     * through the configured UUIDv7 generator when the entity
     * is persisted.
     *
     * <p>New organizations are active by default. Audit identifiers,
     * timestamps, and the optimistic locking version are managed
     * separately and are not supplied by callers.
     *
     * @param name required organization name
     * @param description optional organization description
     */
    public Organization(String name, String description) {
        this.name = name;
        this.description = description;
    }

    /**
     * Initializes persistence timestamps before the organization
     * is inserted into the database.
     *
     * <p>Both timestamps receive the same UTC value so that a newly
     * created organization has consistent creation and modification
     * times.
     *
     * <p>Hibernate invokes this callback automatically during
     * the entity persistence lifecycle.
     */
    @PrePersist
    protected void onCreate() {
        OffsetDateTime now = OffsetDateTime.now(ZoneOffset.UTC);
        createdAt = now;
        updatedAt = now;
    }

    /**
     * Refreshes the modification timestamp before Hibernate
     * updates an existing organization record.
     *
     * <p>The creation timestamp remains unchanged to preserve
     * the original creation time.
     *
     * <p>Hibernate invokes this callback when an entity update
     * is scheduled during persistence.
     */
    @PreUpdate
    protected void onUpdate() {
        updatedAt = OffsetDateTime.now(ZoneOffset.UTC);
    }

    /**
     * Returns the organization's unique identifier.
     *
     * @return PostgreSQL-generated UUIDv7 identifier, or {@code null}
     *         before persistence
     */
    public UUID getOrganizationId() {
        return organizationId;
    }

    /**
     * Returns the organization name.
     *
     * @return organization name
     */
    public String getName() {
        return name;
    }

    /**
     * Returns the optional organization description.
     *
     * @return description, or {@code null} if none is provided
     */
    public String getDescription() {
        return description;
    }

    /**
     * Indicates whether the organization is active.
     *
     * @return {@code true} if active; otherwise {@code false}
     */
    public boolean isActive() {
        return active;
    }

    /**
     * Returns the identifier of the user who created the organization.
     *
     * @return creator identifier, or {@code null} if unavailable
     */
    public UUID getCreatedByUserId() {
        return createdByUserId;
    }

    /**
     * Returns the identifier of the user who last modified the organization.
     *
     * @return last modifying user identifier, or {@code null} if unavailable
     */
    public UUID getUpdatedByUserId() {
        return updatedByUserId;
    }

    /**
     * Returns the creation timestamp.
     *
     * @return creation timestamp, or {@code null} before persistence
     */
    public OffsetDateTime getCreatedAt() {
        return createdAt;
    }

    /**
     * Returns the last modification timestamp.
     *
     * @return modification timestamp, or {@code null} before persistence
     */
    public OffsetDateTime getUpdatedAt() {
        return updatedAt;
    }

    /**
     * Returns the optimistic locking version.
     *
     * @return Hibernate-managed version, or {@code null}
     *         before persistence
     */
    public Long getVersion() {
        return version;
    }

    /**
     * Updates the organization's editable business information.
     *
     * <p>The service layer is responsible for validating the
     * supplied values before invoking this method.
     *
     * <p>Organization identity, active status, audit attribution,
     * timestamps, and optimistic locking version are not modified
     * directly by this operation.
     *
     * <p>When Hibernate detects changes to a managed entity,
     * the {@code @PreUpdate} lifecycle callback refreshes
     * the modification timestamp.
     *
     * @param name validated organization name
     * @param description optional organization description
     */
    public void updateDetails(String name, String description) {
        this.name = name;
        this.description = description;
    }

}
