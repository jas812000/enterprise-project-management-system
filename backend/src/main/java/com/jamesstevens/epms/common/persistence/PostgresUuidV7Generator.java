package com.jamesstevens.epms.common.persistence;

import org.hibernate.engine.spi.SharedSessionContractImplementor;
import org.hibernate.generator.BeforeExecutionGenerator;
import org.hibernate.generator.EventType;

import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.EnumSet;
import java.util.UUID;

/**
 * Hibernate identifier generator that obtains UUIDv7 values
 * directly from PostgreSQL.
 *
 * <p>EPMS uses PostgreSQL 18 or later, which provides the native
 * {@code uuidv7()} function. This generator uses that function
 * instead of generating identifiers in application code.
 *
 * <p>Identifiers are generated before Hibernate executes an
 * entity INSERT. The generated UUID is then included in the
 * INSERT statement.
 *
 * <p>The generator uses the current Hibernate session's JDBC
 * connection, allowing identifier generation to participate
 * in the same database transaction as the entity operation.
 *
 * <p>This class is intended for reuse by EPMS entities that
 * require PostgreSQL-generated UUIDv7 identifiers.
 */
public class PostgresUuidV7Generator implements BeforeExecutionGenerator {

    /**
     * Generates a UUIDv7 identifier using PostgreSQL.
     *
     * @param session current Hibernate session
     * @param owner entity receiving the generated identifier
     * @param currentValue existing identifier value, if any
     * @param eventType Hibernate event triggering generation
     * @return UUIDv7 identifier generated by PostgreSQL
     */
    @Override
    public Object generate(
            SharedSessionContractImplementor session,
            Object owner,
            Object currentValue,
            EventType eventType
    ) {
        return session.doReturningWork(connection -> {
            try (PreparedStatement statement =
                         connection.prepareStatement("SELECT uuidv7()");
                 ResultSet resultSet = statement.executeQuery()) {

                if (!resultSet.next()) {
                    throw new SQLException(
                            "PostgreSQL did not return a UUIDv7 identifier"
                    );
                }

                return resultSet.getObject(1, UUID.class);
            }
        });
    }

    /**
     * Specifies the Hibernate events that trigger generation.
     *
     * <p>Organization identifiers are generated only when
     * inserting a new entity, never when updating an existing one.
     *
     * @return an event set containing INSERT
     */
    @Override
    public EnumSet<EventType> getEventTypes() {
        return EnumSet.of(EventType.INSERT);
    }
}
